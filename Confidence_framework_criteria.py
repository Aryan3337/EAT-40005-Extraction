def chunk_paper_for_confidence(text: str) -> List[str]:
    words = text.split()
    chunks = []
    start = 0
    while start < len(words):
        end = min(start + CONFIDENCE_CHUNK_WORD_SIZE, len(words))
        chunks.append(" ".join(words[start:end]))
        start += CONFIDENCE_CHUNK_WORD_SIZE - CONFIDENCE_CHUNK_OVERLAP
    return chunks


def build_confidence_user_prompt(
    chunk_text: str,
    metadata: Dict[str, Any],
    chunk_num: int,
    total_chunks: int,
) -> str:
    authors = metadata.get("authors", "")
    if isinstance(authors, list):
        authors = ", ".join(str(a) for a in authors)

    meta_str = "\n".join([
        f"Title: {metadata.get('title') or 'Unknown'}",
        f"Authors: {authors or 'Unknown'}",
        f"Year: {metadata.get('year') or 'Unknown'}",
        f"Journal: {metadata.get('journal') or 'Unknown'}",
        f"DOI: {metadata.get('doi') or 'Unknown'}",
    ])

    return f"""## Paper Metadata
{meta_str}

## Paper Excerpt (chunk {chunk_num} of {total_chunks})
{chunk_text}

Evaluate this excerpt against all four criteria and return only the required JSON."""


def extract_json_object(raw: str) -> Optional[Dict[str, Any]]:
    cleaned = re.sub(r"```json|```", "", raw).strip()
    cleaned = re.sub(r"<think>.*?</think>", "", cleaned,
                     flags=re.DOTALL | re.IGNORECASE).strip()
    match = re.search(r"\{.*\}", cleaned, re.DOTALL)
    if not match:
        return None
    try:
        return json.loads(match.group())
    except json.JSONDecodeError:
        return None


def call_confidence_ollama(
    system_prompt: str,
    user_prompt: str,
    model: str,
    retries: int = 2,
) -> Optional[str]:
    for attempt in range(retries):
        try:
            response = requests.post(
                OLLAMA_URL,
                json={
                    "model": model,
                    "messages": [
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt},
                    ],
                    "stream": False,
                    "options": {
                        "temperature": 0.1,
                        "num_predict": 2048,
                    },
                },
                timeout=300,
            )

            if response.status_code == 200:
                return response.json().get("message", {}).get("content", "")

            print(
                f"   Ollama returned status {response.status_code} "
                f"(attempt {attempt + 1})"
            )

        except requests.exceptions.ConnectionError:
            print("   Cannot connect to Ollama. Is 'ollama serve' running?")
        except Exception as e:
            print(f"   Ollama error: {e}")

        time.sleep(2)

    return None


def fallback_confidence_criteria() -> List[CriterionResult]:
    specs = [
        ("Structural Completeness", 20, True),
        ("Peer Review Signals", 20, False),
        ("Authorship & Community Alignment (IKAT)", 25, True),
        ("Ethical Source Handling & Consent", 15, True),
    ]

    return [
        CriterionResult(
            name=name,
            score=0,
            max_score=max_score,
            passed=False,
            justification="Model evaluation failed — could not connect to Ollama or parse the response.",
            evaluated_by="fallback",
            flags=["Model unavailable"],
            hard_fail=hard_fail,
        )
        for name, max_score, hard_fail in specs
    ]


def evaluate_model_criteria(
    paper_text: str,
    metadata: Dict[str, Any],
    model: str,
) -> List[CriterionResult]:
    system_prompt = build_confidence_system_prompt()
    chunks = chunk_paper_for_confidence(paper_text)

    expected = [
        ("Structural Completeness", 20, True),
        ("Peer Review Signals", 20, False),
        ("Authorship & Community Alignment (IKAT)", 25, True),
        ("Ethical Source Handling & Consent", 15, True),
    ]

    if not chunks:
        return fallback_confidence_criteria()

    print(f"   Confidence evaluation: {len(chunks)} chunks.")

    accumulated = {
        name: {
            "scores": [],
            "justifications": [],
            "flags": [],
            "hard_fails": [],
        }
        for name, _, _ in expected
    }

    successful_chunks = 0

    for idx, chunk in enumerate(chunks, 1):
        print(f"   Confidence chunk {idx}/{len(chunks)}...", end=" ", flush=True)

        raw = call_confidence_ollama(
            system_prompt,
            build_confidence_user_prompt(chunk, metadata, idx, len(chunks)),
            model,
        )

        if not raw:
            print("failed")
            continue

        data = extract_json_object(raw)
        if not data or not isinstance(data.get("criteria"), list):
            print("parse error")
            continue

        successful_chunks += 1
        print("OK")

        items_by_name = {
            item.get("name", ""): item
            for item in data["criteria"]
            if isinstance(item, dict)
        }

        for name, max_score, _ in expected:
            item = items_by_name.get(name)
            if not item:
                continue

            try:
                score = int(item.get("score", 0))
            except (TypeError, ValueError):
                score = 0

            score = max(0, min(score, max_score))
            accumulated[name]["scores"].append(score)
            accumulated[name]["justifications"].append(
                str(item.get("justification", ""))
            )

            flags = item.get("flags", [])
            if isinstance(flags, list):
                accumulated[name]["flags"].extend(str(x) for x in flags)

            if item.get("hard_fail_triggered", False):
                accumulated[name]["hard_fails"].append(True)

        time.sleep(0.5)

    if successful_chunks == 0:
        return fallback_confidence_criteria()

    results = []

    for name, max_score, hard_fail in expected:
        acc = accumulated[name]
        scores = acc["scores"]
        score = max(scores) if scores else 0

        if scores:
            best_idx = scores.index(score)
            justification = acc["justifications"][best_idx]
        else:
            justification = "No usable model result was returned for this criterion."

        results.append(
            CriterionResult(
                name=name,
                score=score,
                max_score=max_score,
                passed=score > 0,
                justification=justification,
                evaluated_by="model",
                flags=list(dict.fromkeys(acc["flags"])),
                hard_fail=hard_fail,
                hard_fail_triggered=any(acc["hard_fails"]),
            )
        )

    return results


