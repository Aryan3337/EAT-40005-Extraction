def run_extraction(pdf_path: str, model: str) -> None:
    total_start = time.time()

    print("=" * 70)
    print("Knowledge Graph Extraction – DeepSeek")
    print(f"PDF: {pdf_path}")
    print(f"Model: {model}")
    print(f"Started: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print("=" * 70)

    full_text = extract_text_from_pdf(pdf_path)

    if not full_text.strip():
        print("No text extracted.")
        return

    chunks = chunk_text(full_text)
    print(f"\nCreated {len(chunks)} chunks")

    all_triples = []

    for idx, (chunk, page) in enumerate(chunks, 1):
        print(
            f"Chunk {idx}/{len(chunks)} (page ~{page})...",
            end=" ",
            flush=True,
        )

        triples, _ = extract_kg_chunk(chunk, page, model)
        all_triples.extend(triples)
        print(f"got {len(triples)} triples")
        time.sleep(0.2)

    unique = deduplicate(all_triples)
    base_name = Path(pdf_path).stem

    save_csv(unique, f"{base_name}_kg.csv", base_name)
    save_json(unique, f"{base_name}_kg.json", base_name)

    total_time = time.time() - total_start

    print(
        f"\nCOMPLETED! {len(unique)} unique triples "
        f"in {format_time(total_time)}"
    )

    if unique:
        avg_conf = sum(
            t.get("confidence", 0) for t in unique
        ) / len(unique)
        print(f"Average confidence: {avg_conf:.2f}")


