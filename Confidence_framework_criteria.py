def chunk_text(text: str) -> List[Tuple[str, int]]:
    page_pattern = r"(===== Page \d+ =====\n)"
    parts = re.split(page_pattern, text)

    pages = []
    for i in range(1, len(parts), 2):
        if i + 1 >= len(parts):
            continue

        header = parts[i]
        content = parts[i + 1]
        match = re.search(r"===== Page (\d+) =====", header)
        page_num = int(match.group(1)) if match else 0
        pages.append((page_num, content))

    chunks = []

    for page_num, page_content in pages:
        if not page_content.strip():
            continue

        start = 0
        length = len(page_content)

        while start < length:
            end = min(start + KG_CHUNK_SIZE, length)
            chunks.append((page_content[start:end].strip(), page_num))
            start += KG_CHUNK_SIZE - KG_CHUNK_OVERLAP

    return chunks


def strip_deepseek_reasoning(raw: str) -> str:
    """
    Preserve the original working parser behaviour while also removing
    <think> blocks when a newer DeepSeek response format is returned.
    """
    raw = re.sub(r"<think>.*?</think>", "", raw,
                 flags=re.DOTALL | re.IGNORECASE)

    # Original working behaviour: discard text before the first structured
    # triple delimiter.
    for marker in ["(", "[", "{"]:
        idx = raw.find(marker)
        if idx != -1:
            raw = raw[idx:]
            break

    raw = re.sub(r"^```(?:cypher|json)?\n?", "", raw)
    raw = re.sub(r"\n?```$", "", raw)
    return raw.strip()


def make_kg_prompt(chunk: str) -> str:
    return f"""Read the paper and extract knowledge graph triples in these steps:
1. Identify informative sentences
2. Identify the main subject of each sentence
3. Extract as Subject–Predicate–Object. They should have a format like:
   (GaroWomen)-[ARE_KNOWN_AS]->(SkilledBeauticians)
4. Each triple needs to be referenced to a sentence, so extract the location
   of the sentence alongside the triple
5. Estimate a confidence score between 0.0 and 1.0 indicating how explicitly
   the sentence supports the triple:
   - 1.0 = the sentence directly states the triple verbatim
   - 0.8-0.9 = clearly implies the triple with slight paraphrasing
   - 0.5-0.7 = indirectly supports the triple, some inference needed
   - 0.0-0.4 = weak or ambiguous support, high inference

Output each triple and its reference and confidence on one line in this exact format:
(Subject)-[PREDICATE]->(Object) | Location: "sentence text" (Page X) | confidence: 0.95

Rules:
- Predicates: UPPER_CASE_WITH_UNDERSCORES
- Only extract explicit facts. No inference.
- If no triples, output nothing.

Passage:
{chunk}
"""


def parse_triples_with_reference(
    output: str,
    page_num: int,
) -> List[Dict[str, Any]]:
    triples = []

    for line in output.split("\n"):
        line = line.strip()

        triple_match = re.search(
            r"\(([^)]+)\)\s*-\s*\[:?([^\]]+)\]\s*->\s*\(([^)]+)\)",
            line,
        )

        if not triple_match:
            continue

        subject = triple_match.group(1).strip()
        predicate = triple_match.group(2).strip().upper()
        obj = triple_match.group(3).strip()

        ref_match = re.search(
            r'\|\s*Location:\s*["]?(.*?)["]?(?:\s*\(Page\s*(\d+)\))?',
            line,
            re.IGNORECASE,
        )

        if ref_match:
            sentence_ref = ref_match.group(1).strip()
            ref_page = ref_match.group(2) or str(page_num)
        else:
            parts = line.split("|", 1)
            sentence_ref = parts[1].strip() if len(parts) > 1 else "NO_REFERENCE"
            ref_page = str(page_num)

        confidence_match = re.search(
            r"confidence:\s*([0-9]*\.?[0-9]+)",
            line,
            re.IGNORECASE,
        )

        if confidence_match:
            confidence = max(
                0.0,
                min(1.0, float(confidence_match.group(1))),
            )
        else:
            confidence = 0.5

        triples.append({
            "subject": subject,
            "predicate": predicate,
            "object": obj,
            "source_section": f"Page {ref_page}",
            "confidence": confidence,
            "passage": f"({subject})-[:{predicate}]->({obj})",
            "sentence_ref": sentence_ref,
        })

    return triples


def extract_kg_chunk(
    chunk: str,
    page_num: int,
    model: str,
    retries: int = 2,
) -> Tuple[List[Dict[str, Any]], float]:
    prompt = make_kg_prompt(chunk)
    start_time = time.time()

    for attempt in range(retries):
        try:
            response = requests.post(
                KG_URL,
                json={
                    "model": model,
                    "prompt": prompt,
                    "stream": False,
                    "options": {
                        "temperature": 0.0,
                        "num_predict": 2048,
                    },
                },
                timeout=150,
            )

            elapsed = time.time() - start_time

            if response.status_code != 200:
                print(
                    f"HTTP {response.status_code} "
                    f"(attempt {attempt + 1})"
                )
                continue

            raw = response.json().get("response", "")
            cleaned = strip_deepseek_reasoning(raw)
            triples = parse_triples_with_reference(cleaned, page_num)

            if triples:
                return triples, elapsed

        except requests.exceptions.ConnectionError:
            print("Cannot connect to Ollama. Is 'ollama serve' running?")
        except Exception as e:
            print(f"Attempt {attempt + 1} error: {e}")

        time.sleep(1)

    return [], time.time() - start_time


def deduplicate(triples: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    seen = {}

    for triple in triples:
        key = (
            f"{triple['subject'].lower()}|"
            f"{triple['predicate']}|"
            f"{triple['object'].lower()}"
        )

        if key not in seen:
            seen[key] = triple
            continue

        current_conf = triple.get("confidence", 0)
        existing_conf = seen[key].get("confidence", 0)

        if current_conf > existing_conf:
            seen[key] = triple
        elif (
            current_conf == existing_conf
            and len(triple.get("sentence_ref", ""))
            > len(seen[key].get("sentence_ref", ""))
        ):
            seen[key] = triple

    return list(seen.values())


def save_csv(triples: List[Dict[str, Any]], path: str, paper: str) -> None:
    fields = [
        "extraction_number", "paper", "subject", "predicate", "object",
        "source_section", "confidence", "passage", "sentence_ref",
    ]

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()

        for idx, triple in enumerate(triples, 1):
            writer.writerow({
                "extraction_number": idx,
                "paper": paper,
                "subject": triple.get("subject", ""),
                "predicate": triple.get("predicate", ""),
                "object": triple.get("object", ""),
                "source_section": triple.get("source_section", "Unknown"),
                "confidence": triple.get("confidence", 0.5),
                "passage": triple.get("passage", ""),
                "sentence_ref": triple.get("sentence_ref", ""),
            })


def save_json(triples: List[Dict[str, Any]], path: str, paper: str) -> None:
    data = []

    for idx, triple in enumerate(triples, 1):
        data.append({
            "extraction_number": idx,
            "paper": paper,
            "subject": triple["subject"],
            "predicate": triple["predicate"],
            "object": triple["object"],
            "source_section": triple["source_section"],
            "confidence": triple.get("confidence", 0.5),
            "passage": triple["passage"],
            "sentence_ref": triple["sentence_ref"],
        })

    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


def format_time(seconds: float) -> str:
    if seconds < 60:
        return f"{seconds:.2f} sec"
    return f"{int(seconds // 60)}m {seconds % 60:.2f}s"


