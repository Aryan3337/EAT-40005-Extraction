def get_arg(name: str, default: str = "") -> str:
    if name in sys.argv:
        idx = sys.argv.index(name)
        if idx + 1 < len(sys.argv):
            return sys.argv[idx + 1]
    return default


def print_confidence_result(result: EvaluationResult) -> None:
    print("\n" + "=" * 95)
    print(f"{result.outcome.value} — {result.paper_name}")
    print(f"Model: {result.model_used}")

    if result.total_score >= 0:
        print(
            f"ACCUMULATED SCORE: {result.accumulated_score}/"
            f"{result.max_possible} ({result.score_pct}%)"
        )
        print(
            f"Bands: REJECTED < {REJECT_THRESHOLD} | "
            f"MANUAL REVIEW {REJECT_THRESHOLD}-{REVIEW_THRESHOLD} | "
            f"APPROVED > {REVIEW_THRESHOLD}"
        )

    print("-" * 95)

    print(
        f"{'#':<4}{'Criterion':<45}{'Score':<10}"
        f"{'Hard Fail?':<14}{'Status':<10}"
    )
    print("-" * 95)

    for idx, criterion in enumerate(result.criteria, 1):
        if not criterion.hard_fail:
            hard_status = "NO"
        elif criterion.hard_fail_triggered:
            hard_status = "TRIGGERED"
        else:
            hard_status = "YES"

        status = (
            "FAIL" if criterion.hard_fail_triggered
            else "OK" if criterion.passed
            else "LOW"
        )

        print(
            f"{idx:<4}{criterion.name:<45}"
            f"{criterion.score}/{criterion.max_score:<7}"
            f"{hard_status:<14}{status:<10}"
        )

    print("-" * 95)

    if result.hard_fail_criteria:
        print(
            "HARD FAILS TRIGGERED: " +
            ", ".join(c.name for c in result.hard_fail_criteria)
        )
    else:
        print("HARD FAILS TRIGGERED: None")

    if result.rejection_reason:
        print(f"Reason: {result.rejection_reason}")
    if result.review_reason:
        print(f"Reason: {result.review_reason}")

    print("=" * 95)


def main() -> None:
    if len(sys.argv) < 2:
        print(
            "Usage: python script_updated.py <pdf_path> "
            "[model_name] [--title ...] [--authors ...] "
            "[--year ...] [--journal ...] [--doi ...]"
        )
        sys.exit(1)

    pdf_path = sys.argv[1]

    model = "deepseek-r1:7b"
    if len(sys.argv) > 2 and not sys.argv[2].startswith("--"):
        model = sys.argv[2]

    metadata = {
        "title": get_arg("--title"),
        "authors": get_arg("--authors"),
        "year": get_arg("--year"),
        "journal": get_arg("--journal"),
        "doi": get_arg("--doi"),
    }

    # --------------------------------------------------------
    # Check previous confidence status.
    # --------------------------------------------------------

    outcome, timestamp, log_path = get_paper_status(pdf_path)

    if outcome == EvaluationOutcome.APPROVED.value:
        print(f"\nPaper previously APPROVED (log: {log_path})")
        print("Running extraction automatically...")
        run_extraction(pdf_path, model)
        return

    if outcome == EvaluationOutcome.REJECTED.value:
        print(f"\nPaper previously REJECTED (log: {log_path})")
        answer = input("Override and extract anyway? (y/N): ").strip().lower()

        if answer == "y":
            run_extraction(pdf_path, model)
        else:
            print("Extraction skipped.")
        return

    if outcome == EvaluationOutcome.MANUAL_REVIEW.value:
        print(f"\nPaper previously marked MANUAL REVIEW (log: {log_path})")
        answer = input("Override and extract anyway? (y/N): ").strip().lower()

        if answer == "y":
            run_extraction(pdf_path, model)
        else:
            print("Extraction skipped.")
        return

    # --------------------------------------------------------
    # No previous evaluation.
    # --------------------------------------------------------

    print("\n" + "=" * 70)
    print("No previous confidence evaluation found for this paper.")
    print("Options:")
    print("  1) Run updated 8-criterion confidence check")
    print("  2) Extract anyway (bypass confidence)")
    print("  3) Exit")

    choice = input("Enter choice (1/2/3): ").strip()

    if choice == "1":
        result = run_confidence_check(
            pdf_path,
            metadata=metadata,
            model=model,
        )
        print_confidence_result(result)

        if result.outcome == EvaluationOutcome.REJECTED:
            print("\nExtraction skipped.")
            sys.exit(1)

        if result.outcome == EvaluationOutcome.MANUAL_REVIEW:
            answer = input(
                "\nOverride manual review and extract anyway? (y/N): "
            ).strip().lower()

            if answer != "y":
                print("Extraction skipped.")
                sys.exit(2)

            print("Manual override accepted — proceeding with extraction.")

        run_extraction(pdf_path, model)

    elif choice == "2":
        print(
            "\nWARNING: Bypassing confidence check — "
            "extraction may produce low-quality results."
        )
        run_extraction(pdf_path, model)

    else:
        print("Exiting.")
        sys.exit(0)


if __name__ == "__main__":
    main()