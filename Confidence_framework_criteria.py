class EvaluationOutcome(str, Enum):
    APPROVED = "APPROVED"
    MANUAL_REVIEW = "MANUAL_REVIEW"
    REJECTED = "REJECTED"


@dataclass
class CriterionResult:
    name: str
    score: int
    max_score: int
    passed: bool
    justification: str
    evaluated_by: str
    flags: List[str] = field(default_factory=list)
    hard_fail: bool = False
    hard_fail_triggered: bool = False


@dataclass
class EvaluationResult:
    paper_path: str
    paper_name: str
    timestamp: str
    total_score: int
    max_possible: int
    outcome: EvaluationOutcome
    criteria: List[CriterionResult] = field(default_factory=list)
    rejection_reason: Optional[str] = None
    review_reason: Optional[str] = None
    log_path: Optional[str] = None
    review_queue_path: Optional[str] = None
    model_used: str = OLLAMA_MODEL

    @property
    def score_pct(self) -> float:
        return round(self.total_score / self.max_possible * 100, 1) if self.max_possible else 0.0

    @property
    def accumulated_score(self) -> int:
        return self.total_score

    @property
    def hard_fail_criteria(self) -> List[CriterionResult]:
        return [c for c in self.criteria if c.hard_fail and c.hard_fail_triggered]


