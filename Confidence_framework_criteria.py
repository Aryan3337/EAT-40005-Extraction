def check_metadata_completeness(metadata: Dict[str, Any]) -> CriterionResult:
    fields = {
        "title": 2,
        "authors": 2,
        "year": 2,
        "journal": 2,
        "doi": 2,
    }

    found = [f for f in fields if metadata.get(f)]
    missing = [f for f in fields if not metadata.get(f)]
    score = sum(fields[f] for f in found)

    return CriterionResult(
        name="Metadata Completeness",
        score=score,
        max_score=10,
        passed=score >= 5,
        justification=f"Metadata present: {found}. Missing: {missing}.",
        evaluated_by="code",
        flags=[f"Missing: {f}" for f in missing],
    )


def check_red_flags(text_lower: str) -> CriterionResult:
    found = [p for p in RED_FLAG_PHRASES if p in text_lower]

    has_references = bool(
        re.search(r"\breferences\b|\bbibliography\b|\breference list\b", text_lower)
    )

    ai_only = (
        bool(found)
        and all(p in {
            "as an ai language model",
            "generated by chatgpt",
            "generated by artificial intelligence",
        } for p in found)
    )

    if not found:
        score, triggered = 5, False
        justification = "No red-flag phrases detected."
    elif ai_only and has_references:
        score, triggered = 3, False
        justification = (
            "AI-generation indicators were found, but references are also "
            "present. Flagged for caution rather than hard failure."
        )
    else:
        score, triggered = 0, True
        justification = "Non-academic or serious source red flags were detected."

    return CriterionResult(
        name="Red Flag Absence",
        score=score,
        max_score=5,
        passed=not triggered,
        justification=justification,
        evaluated_by="code",
        flags=[f"Red flag: '{p}'" for p in found],
        hard_fail=True,
        hard_fail_triggered=triggered,
    )


def _has_unnegated_match(text: str, phrase: str, window_chars: int = 40) -> bool:
    start = 0
    while True:
        idx = text.find(phrase, start)
        if idx == -1:
            return False

        preceding = text[max(0, idx - window_chars):idx]
        if not any(cue in preceding for cue in NEGATION_CUES):
            return True

        start = idx + len(phrase)


def _dedupe_substring_hits(hits: List[str]) -> List[str]:
    hits_sorted = sorted(set(hits), key=len, reverse=True)
    kept = []
    for hit in hits_sorted:
        if not any(hit != existing and hit in existing for existing in kept):
            kept.append(hit)
    return kept


def check_data_driven_evidence(text_lower: str) -> Dict[str, Any]:
    data_hits = _dedupe_substring_hits([
        s for s in DATA_DRIVEN_SIGNALS
        if _has_unnegated_match(text_lower, s)
    ])

    experience_hits = _dedupe_substring_hits([
        s for s in EXPERIENCE_REPORT_SIGNALS
        if s in text_lower
    ])

    if experience_hits and not data_hits:
        verdict = "experience_report"
    elif experience_hits and data_hits and len(experience_hits) > len(data_hits):
        verdict = "experience_leaning"
    elif data_hits:
        verdict = "data_driven"
    else:
        verdict = "undetermined"

    return {
        "verdict": verdict,
        "data_driven_signals_found": data_hits,
        "experience_signals_found": experience_hits,
    }


def check_experience_report_identification(text_lower: str) -> CriterionResult:
    scan = check_data_driven_evidence(text_lower)
    verdict = scan["verdict"]
    experience_hits = scan["experience_signals_found"]
    data_hits = scan["data_driven_signals_found"]

    if verdict == "experience_report":
        score = 5
        justification = (
            "Paper appears narrative/experiential with no clear "
            "data-collection or methodology evidence."
        )
    elif verdict == "experience_leaning":
        score = 3
        justification = (
            "Experiential or reflective language is stronger than the "
            "detected methodology/data-driven signals."
        )
    elif verdict == "data_driven":
        score = 0
        justification = (
            "Paper appears to be a conventional data-driven research "
            "paper rather than an experience report."
        )
    else:
        score = 0
        justification = (
            "No strong experience-report or data-driven signals were detected."
        )

    flags = []
    if experience_hits:
        flags.append(f"Experience signals: {experience_hits[:8]}")
    if data_hits:
        flags.append(f"Data-driven signals: {data_hits[:8]}")

    return CriterionResult(
        name="Experience Report Identification",
        score=score,
        max_score=5,
        passed=True,
        justification=justification,
        evaluated_by="code",
        flags=flags,
    )


def check_domain_relevance(text_lower: str) -> CriterionResult:
    found = [k for k in COMMUNITY_KEYWORDS if k.lower() in text_lower]

    return CriterionResult(
        name="Domain Relevance",
        score=0,
        max_score=0,
        passed=True,
        justification=(
            f"Community/domain-related keywords were detected: {found}."
            if found else
            "No configured community/domain keywords were detected. "
            "This criterion is logged only and does not affect scoring."
        ),
        evaluated_by="code",
        flags=[] if found else ["No configured domain keywords found"],
    )


