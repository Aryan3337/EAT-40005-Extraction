def get_paper_status(pdf_path: str) -> Tuple[Optional[str], Optional[str], Optional[str]]:
    """
    Reads the NEW confidence_logs layout:
      confidence_logs/approved/
      confidence_logs/rejected/
      confidence_logs/review/

    Also understands the old rejection_logs layout so existing papers
    are not silently re-evaluated.
    """
    paper_stem = Path(pdf_path).stem

    candidates = []

    for directory in (APPROVED_DIR, REJECTED_DIR, REVIEW_DIR):
        if directory.exists():
            candidates.extend(directory.glob(f"*_{paper_stem}.json"))

    # Backward compatibility with the original working script.
    old_dir = Path("rejection_logs")
    if old_dir.exists():
        candidates.extend(old_dir.glob(f"*_*_{paper_stem}.json"))

    if not candidates:
        return None, None, None

    candidates.sort(key=lambda f: f.stat().st_mtime, reverse=True)
    latest = candidates[0]

    try:
        data = json.loads(latest.read_text(encoding="utf-8"))
        outcome = data.get("outcome")
        timestamp = data.get("timestamp") or datetime.fromtimestamp(
            latest.stat().st_mtime
        ).strftime("%Y%m%d_%H%M%S")
        return outcome, timestamp, str(latest)
    except Exception:
        return None, None, None


def save_evaluation_log(result: EvaluationResult, log_type: str) -> Path:
    LOG_DIR.mkdir(parents=True, exist_ok=True)

    subdir = {
        "approval": APPROVED_DIR,
        "rejection": REJECTED_DIR,
        "review": REVIEW_DIR,
    }.get(log_type, LOG_DIR)

    subdir.mkdir(parents=True, exist_ok=True)

    safe_name = re.sub(r"[^\w\-]", "_", Path(result.paper_path).stem)[:50]
    log_path = subdir / f"{result.timestamp}_{log_type}_{safe_name}.json"

    data = {
        "paper": result.paper_path,
        "paper_name": result.paper_name,
        "timestamp": result.timestamp,
        "model_used": result.model_used,
        "outcome": result.outcome.value,
        "accumulated_score": result.accumulated_score,
        "total_score": result.total_score,
        "max_possible": result.max_possible,
        "score_pct": result.score_pct,
        "hard_fail_count": len(result.hard_fail_criteria),
        "hard_fail_criteria": [c.name for c in result.hard_fail_criteria],
        "thresholds": {
            "reject_below": REJECT_THRESHOLD,
            "manual_review_band": f"{REJECT_THRESHOLD}-{REVIEW_THRESHOLD}",
            "auto_approve_above": REVIEW_THRESHOLD,
        },
        "rejection_reason": result.rejection_reason,
        "review_reason": result.review_reason,
        "criteria": [
            {
                "name": c.name,
                "score": c.score,
                "max_score": c.max_score,
                "passed": c.passed,
                "hard_fail": c.hard_fail,
                "hard_fail_triggered": c.hard_fail_triggered,
                "evaluated_by": c.evaluated_by,
                "justification": c.justification,
                "flags": c.flags,
            }
            for c in result.criteria
        ],
        "next_steps": (
            "REJECTED — paper skipped. Review the hard-fail criteria and "
            "criterion justifications before reconsidering this source."
            if log_type == "rejection"
            else
            "MANUAL REVIEW — extraction is held pending human review."
            if log_type == "review"
            else
            "APPROVED — paper passed the scoreboard and is ready for "
            "knowledge graph extraction."
        ),
    }

    log_path.write_text(
        json.dumps(data, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    return log_path


def append_review_queue(result: EvaluationResult) -> Path:
    write_header = not REVIEW_QUEUE_FILE.exists()

    with open(REVIEW_QUEUE_FILE, "a", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)

        if write_header:
            writer.writerow([
                "timestamp", "paper_name", "paper_path", "model_used",
                "accumulated_score", "max_possible", "score_pct",
                "hard_fail_criteria", "review_reason", "status",
                "override_by", "override_note",
            ])

        writer.writerow([
            result.timestamp,
            result.paper_name,
            result.paper_path,
            result.model_used,
            result.accumulated_score,
            result.max_possible,
            result.score_pct,
            "; ".join(c.name for c in result.hard_fail_criteria),
            result.review_reason,
            "PENDING",
            "",
            "",
        ])

    return REVIEW_QUEUE_FILE


def run_confidence_check(
    pdf_path: str,
    metadata: Dict[str, Any],
    model: str,
) -> EvaluationResult:
    paper_path = Path(pdf_path)
    paper_name = paper_path.stem
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    print(f"\n1. Confidence evaluation for {paper_name}...")

    try:
        full_text = extract_text_from_pdf(str(paper_path))
        text_lower = normalise_text(full_text)
        print(f"   Extracted {len(text_lower.split())} words.")
    except Exception as e:
        print(f"   Text extraction failed: {e}")
        full_text = ""
        text_lower = ""

    print("2. Model evaluation (Criteria 1–4)...")
    model_criteria = evaluate_model_criteria(full_text, metadata, model)

    print("3. Code evaluation (Criteria 5–8)...")
    code_criteria = [
        check_metadata_completeness(metadata),
        check_red_flags(text_lower),
        check_experience_report_identification(text_lower),
        check_domain_relevance(text_lower),
    ]

    for c in code_criteria:
        print(f"   {c.name}: {c.score}/{c.max_score}")

    all_criteria = model_criteria + code_criteria

    total_score = sum(c.score for c in all_criteria)
    max_possible = sum(c.max_score for c in all_criteria)

    hard_fails = [c for c in all_criteria if c.hard_fail and c.hard_fail_triggered]

    if hard_fails:
        outcome = EvaluationOutcome.REJECTED
        rejection_reason = (
            "Hard-fail criterion triggered: " +
            "; ".join(f"{c.name} — {c.justification}" for c in hard_fails)
        )
        review_reason = None

    elif total_score < REJECT_THRESHOLD:
        outcome = EvaluationOutcome.REJECTED
        rejection_reason = (
            f"Accumulated score {total_score}/{max_possible} "
            f"({round(total_score / max_possible * 100, 1)}%) "
            f"is below the reject threshold of {REJECT_THRESHOLD}."
        )
        review_reason = None

    elif total_score <= REVIEW_THRESHOLD:
        outcome = EvaluationOutcome.MANUAL_REVIEW
        rejection_reason = None
        review_reason = (
            f"Accumulated score {total_score}/{max_possible} "
            f"({round(total_score / max_possible * 100, 1)}%) "
            f"is in the manual review band "
            f"({REJECT_THRESHOLD}-{REVIEW_THRESHOLD})."
        )

    else:
        outcome = EvaluationOutcome.APPROVED
        rejection_reason = None
        review_reason = None

    result = EvaluationResult(
        paper_path=str(paper_path),
        paper_name=paper_name,
        timestamp=timestamp,
        total_score=total_score,
        max_possible=max_possible,
        outcome=outcome,
        criteria=all_criteria,
        rejection_reason=rejection_reason,
        review_reason=review_reason,
        model_used=model,
    )

    if outcome == EvaluationOutcome.REJECTED:
        result.log_path = str(save_evaluation_log(result, "rejection"))
        print(f"4. REJECTED — {rejection_reason}")
        print(f"   Log: {result.log_path}")

    elif outcome == EvaluationOutcome.MANUAL_REVIEW:
        result.log_path = str(save_evaluation_log(result, "review"))
        result.review_queue_path = str(append_review_queue(result))
        print(f"4. MANUAL REVIEW — {review_reason}")
        print(f"   Log: {result.log_path}")
        print(f"   Review queue: {result.review_queue_path}")

    else:
        result.log_path = str(save_evaluation_log(result, "approval"))
        print(
            f"4. APPROVED — accumulated score "
            f"{total_score}/{max_possible} ({result.score_pct}%)"
        )
        print(f"   Log: {result.log_path}")

    return result


