# 3. Ollama API call
# ============================================================

def call_ollama(
    system_prompt: str,
    user_prompt: str,
    retries: int = 2
) -> Optional[str]:
    for attempt in range(retries):
        try:
            response = requests.post(
                OLLAMA_URL,
                json={
                    "model": OLLAMA_MODEL,
                    "messages": [
                        {"role": "system", "content": system_prompt},
                        {"role": "user", "content": user_prompt},
                    ],
                    "stream": False,
                    "format": {
                        "type": "object",
                        "properties": {
                            "criteria": {
                                "type": "array",
                                "minItems": 4,
                                "maxItems": 4,
                                "items": {
                                    "type": "object",
                                    "properties": {
                                        "name": {
                                            "type": "string",
                                            "enum": [
                                                "Structural Completeness",
                                                "Peer Review Signals",
                                                "Authorship & Community Alignment (IKAT)",
                                                "Ethical Source Handling & Consent"
                                            ]
                                        },
                                        "score": {
                                            "type": "integer",
                                            "minimum": 0,
                                            "maximum": 25
                                        },
                                        "max_score": {
                                            "type": "integer"
                                        },
                                        "justification": {
                                            "type": "string"
                                        },
                                        "flags": {
                                            "type": "array",
                                            "items": {
                                                "type": "string"
                                            }
                                        },
                                        "hard_fail_triggered": {
                                            "type": "boolean"
                                        }
                                    },
                                    "required": [
                                        "name",
                                        "score",
                                        "max_score",
                                        "justification",
                                        "flags",
                                        "hard_fail_triggered"
                                    ]
                                }
                            },
                            "overall_recommendation": {
                                "type": "string"
                            }
                        },
                        "required": ["criteria"]
                    },
                    "options": {
                        "temperature": 0.1,
                        "num_predict": 2048,
                    }
                },
                timeout=300
            )

            if response.status_code == 200:
                return response.json().get(
                    "message", {}
                ).get("content", "")

            print(
                f"   Ollama returned status {response.status_code} "
                f"(attempt {attempt + 1})"
            )
            print(f"   Response: {response.text[:200]}")

        except requests.exceptions.ConnectionError:
            print(
                "   Cannot connect to Ollama. "
                "Is 'ollama serve' running?"
            )
            if attempt == retries - 1:
                return None

        except Exception as e:
            print(f"   Ollama error: {e}")

        time.sleep(2)

    return None


def parse_model_response(raw: str) -> Optional[List[Dict[str, Any]]]:
    data = extract_json_object(raw)
    if not data:
        return None
    return data.get("criteria", [])


