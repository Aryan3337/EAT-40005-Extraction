def check_metadata_completeness(
    metadata: Dict[str, Any]
) -> CriterionResult:
    field_scores = {
        "title": 2,
        "authors": 2,
        "year": 2,
        "journal": 2,
        "doi": 2,
    }

    score = sum(
        points
        for field_name, points in field_scores.items()
        if metadata.get(field_name)
    )

    found = [
        field_name
        for field_name in field_scores
        if metadata.get(field_name)
    ]

    missing = [
        field_name
        for field_name in field_scores
        if not metadata.get(field_name)
    ]

    return CriterionResult(
        name="Metadata Completeness",
        score=score,
        max_score=10,
        passed=score >= 5,
        justification=(
            f"Metadata present: {found}. "
            f"Missing: {missing}."
        ),
        evaluated_by="code",
        flags=[
            f"Missing: {field_name}"
            for field_name in missing
        ] if missing else [],
        hard_fail=False,
        hard_fail_triggered=False,
    )


def check_red_flags(text_lower: str) -> CriterionResult:
    found = [
        phrase
        for phrase in RED_FLAG_PHRASES
        if phrase in text_lower
    ]

    has_references = bool(
        re.search(
            r"\breferences\b|\bbibliography\b|\breference list\b",
            text_lower
        )
    )

    ai_only = (
        len(found) > 0
        and all(
            phrase in {
                "as an ai language model",
                "generated by chatgpt",
                "generated by artificial intelligence",
            }
            for phrase in found
        )
    )

    if not found:
        score = 5
        triggered = False
        justification = "No red-flag phrases detected."

    elif ai_only and has_references:
        score = 3
        triggered = False
        justification = (
            "AI-generation indicators were found, but references are also "
            "present. Flagged for caution rather than hard failure."
        )

    else:
        score = 0
        triggered = True
        justification = (
            "Non-academic or serious source red flags were detected."
        )

    return CriterionResult(
        name="Red Flag Absence",
        score=score,
        max_score=5,
        passed=not triggered,
        justification=justification,
        evaluated_by="code",
        flags=[
            f"Red flag: '{phrase}'"
            for phrase in found
        ],
        hard_fail=True,
        hard_fail_triggered=triggered,
    )


