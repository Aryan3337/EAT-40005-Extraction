def run_confidence_check(
    pdf_path: str,
    metadata: Optional[Dict[str, Any]] = None,
    override_approve: Optional[str] = None,
) -> EvaluationResult:
    paper_path = Path(pdf_path)
    paper_name = paper_path.stem
    metadata = metadata or {}
    timestamp = datetime.now().strftime(
        "%Y%m%d_%H%M%S"
    )

    if override_approve:
        print(
            f"[OVERRIDE] {paper_name} manually approved: "
            f"{override_approve}"
        )

        return EvaluationResult(
            paper_path=str(paper_path),
            paper_name=paper_name,
            timestamp=timestamp,
            total_score=-1,
            max_possible=100,
            outcome=EvaluationOutcome.APPROVED,
            review_reason=(
                f"Manual override: {override_approve}"
            ),
            model_used=OLLAMA_MODEL,
        )

    print(
        f"1. Extracting text from {paper_name}..."
    )

    try:
        full_text = extract_text_from_pdf(
            str(paper_path)
        )
        text_lower = normalise_text(full_text)

        print(
            f"   Extracted "
            f"{len(text_lower.split())} words."
        )

    except Exception as e:
        print(
            f"   Text extraction failed: {e}"
        )
        full_text = ""
        text_lower = ""

    print(
        "2. Running model evaluation "
        "(Criteria 1–4)..."
    )

    model_criteria = evaluate_with_model(
        full_text,
        metadata
    )

    print(
        "3. Running code evaluation "
        "(Criteria 5–8)..."
    )

    code_criteria = [
        check_metadata_completeness(metadata),
        check_red_flags(text_lower),
        check_experience_report_identification(
            text_lower
        ),
        check_domain_relevance(text_lower),
    ]

    for criterion in code_criteria:
        print(
            f"   {criterion.name}: "
            f"{criterion.score}/"
            f"{criterion.max_score}"
        )

    all_criteria = (
        model_criteria + code_criteria
    )

    # Criterion 8 has max_score=0 and score=0, so the accumulated
    # score remains out of 100.
    total_score = sum(
        criterion.score
        for criterion in all_criteria
    )

    max_possible = sum(
        criterion.max_score
        for criterion in all_criteria
    )

    triggered_hard_fails = [
        criterion
        for criterion in all_criteria
        if (
            criterion.hard_fail
            and criterion.hard_fail_triggered
        )
    ]

    # ========================================================
    # Determine outcome
    # ========================================================

    if triggered_hard_fails:
        outcome = EvaluationOutcome.REJECTED

        rejection_reason = (
            "Hard-fail criterion triggered: "
            + "; ".join(
                f"{criterion.name} — "
                f"{criterion.justification}"
                for criterion in triggered_hard_fails
            )
        )

        review_reason = None

    elif total_score < REJECT_THRESHOLD:
        outcome = EvaluationOutcome.REJECTED

        rejection_reason = (
            f"Accumulated score "
            f"{total_score}/{max_possible} "
            f"({round(total_score / max_possible * 100, 1)}%) "
            f"is below the reject threshold of "
            f"{REJECT_THRESHOLD}."
        )

        review_reason = None

    elif total_score <= REVIEW_THRESHOLD:
        outcome = EvaluationOutcome.MANUAL_REVIEW

        rejection_reason = None

        review_reason = (
            f"Accumulated score "
            f"{total_score}/{max_possible} "
            f"({round(total_score / max_possible * 100, 1)}%) "
            f"is in the manual review band "
            f"({REJECT_THRESHOLD}-{REVIEW_THRESHOLD})."
        )

    else:
        outcome = EvaluationOutcome.APPROVED
        rejection_reason = None
        review_reason = None

    result = EvaluationResult(
        paper_path=str(paper_path),
        paper_name=paper_name,
        timestamp=timestamp,
        total_score=total_score,
        max_possible=max_possible,
        outcome=outcome,
        criteria=all_criteria,
        rejection_reason=rejection_reason,
        review_reason=review_reason,
        model_used=OLLAMA_MODEL,
    )

    # ========================================================
    # Write outputs
    # ========================================================

    if outcome == EvaluationOutcome.REJECTED:
        log_path = save_evaluation_log(
            result,
            "rejection"
        )

        result.log_path = str(log_path)

        print(
            f"4. REJECTED — {rejection_reason}"
        )

        print(f"   Log: {log_path}")

    elif outcome == EvaluationOutcome.MANUAL_REVIEW:
        log_path = save_evaluation_log(
            result,
            "review"
        )

        result.log_path = str(log_path)

        review_queue_path = append_review_queue(
            result
        )

        result.review_queue_path = str(
            review_queue_path
        )

        print(
            f"4. MANUAL REVIEW — {review_reason}"
        )

        print(f"   Log: {log_path}")

        print(
            f"   Review queue: "
            f"{review_queue_path}"
        )

    else:
        log_path = save_evaluation_log(
            result,
            "approval"
        )

        result.log_path = str(log_path)

        print(
            f"4. APPROVED — accumulated score "
            f"{total_score}/{max_possible} "
            f"({result.score_pct}%)"
        )

        print(f"   Log: {log_path}")

    print("Done!")

    return result


