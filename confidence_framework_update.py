# 4. Model-based criteria evaluation (Criteria 1–4)
# ============================================================

def evaluate_with_model(
    paper_text: str,
    metadata: Dict[str, Any]
) -> List[CriterionResult]:
    system_prompt = build_system_prompt()
    chunks = chunk_paper(paper_text)
    total_chunks = len(chunks)

    if not chunks:
        return _fallback_criteria()

    print(
        f"   Split into {total_chunks} chunks of "
        f"~{CHUNK_WORD_SIZE} words each."
    )

    expected = [
        ("Structural Completeness", 20, True),
        ("Peer Review Signals", 20, False),
        ("Authorship & Community Alignment (IKAT)", 25, True),
        ("Ethical Source Handling & Consent", 15, True),
    ]

    accumulated: Dict[str, Dict[str, Any]] = {
        name: {
            "scores": [],
            "justifications": [],
            "flags": [],
            "hard_fails": [],
            "max_score": max_score,
            "hard_fail": hard_fail,
        }
        for name, max_score, hard_fail in expected
    }

    successful_chunks = 0

    for idx, chunk in enumerate(chunks, start=1):
        print(
            f"   Chunk {idx}/{total_chunks}...",
            end=" ",
            flush=True
        )

        user_prompt = build_user_prompt(
            chunk,
            metadata,
            idx,
            total_chunks
        )

        raw = call_ollama(system_prompt, user_prompt)

        print("\n--- RAW MODEL RESPONSE ---")
        print(raw)
        print("--- END RAW MODEL RESPONSE ---\n")

        if not raw:
            print("failed (skipped)")
            continue

        criteria_data = parse_model_response(raw)

        if not criteria_data:
            print("parse error (skipped)")
            print("\n--- RAW MODEL RESPONSE ---")
            print(raw)
            print("--- END RAW MODEL RESPONSE ---\n")
            continue

        successful_chunks += 1
        print("OK")

        items_by_name = {
            item.get("name", ""): item
            for item in criteria_data
            if isinstance(item, dict)
        }

        for name, max_score, _ in expected:
            item = items_by_name.get(name)

            if item is None:
                continue

            try:
                raw_score = int(item.get("score", 0))
                returned_max = int(item.get("max_score", max_score))

                # Some local models return a 0-5 rating even though the
                # framework criterion is worth 15, 20 or 25 points.
                # Convert that rating proportionally to the criterion scale.
                if returned_max > 0 and returned_max != max_score:
                    score = round((raw_score / returned_max) * max_score)
                else:
                    score = raw_score

                score = max(0, min(score, max_score))

            except (TypeError, ValueError, ZeroDivisionError):
                score = 0

            score = max(0, min(score, max_score))

            accumulated[name]["scores"].append(score)
            accumulated[name]["justifications"].append(
                item.get("justification", "")
            )

            flags = item.get("flags", [])
            if isinstance(flags, list):
                accumulated[name]["flags"].extend(
                    str(flag) for flag in flags
                )

            if item.get("hard_fail_triggered", False):
                accumulated[name]["hard_fails"].append(True)

        time.sleep(0.5)

    if successful_chunks == 0:
        print(
            "   All chunks failed — falling back to zero scores."
        )
        return _fallback_criteria()

    print(
        f"   {successful_chunks}/{total_chunks} chunks "
        f"evaluated successfully."
    )

    results = []

    for name, max_score, hard_fail in expected:
        acc = accumulated[name]
        scores = acc["scores"]

        # Same accumulation style as the original framework:
        # keep the strongest evidence found across successful chunks.
        score = max(scores) if scores else 0

        if scores:
            best_idx = scores.index(max(scores))
            justification = (
                acc["justifications"][best_idx]
                if best_idx < len(acc["justifications"])
                else "No justification."
            )
        else:
            justification = (
                "No usable model result was returned for this criterion."
            )

        unique_flags = list(
            dict.fromkeys(acc["flags"])
        )

        results.append(
            CriterionResult(
                name=name,
                score=score,
                max_score=max_score,
                passed=score > 0,
                justification=justification,
                evaluated_by="model",
                flags=unique_flags,
                hard_fail=hard_fail,
                hard_fail_triggered=any(
                    acc["hard_fails"]
                ),
            )
        )

    return results


def _fallback_criteria() -> List[CriterionResult]:
    specs = [
        ("Structural Completeness", 20, True),
        ("Peer Review Signals", 20, False),
        ("Authorship & Community Alignment (IKAT)", 25, True),
        ("Ethical Source Handling & Consent", 15, True),
    ]

    return [
        CriterionResult(
            name=name,
            score=0,
            max_score=max_score,
            passed=False,
            justification=(
                "Model evaluation failed — could not connect to Ollama "
                "or parse the response."
            ),
            evaluated_by="fallback",
            flags=["Model unavailable"],
            hard_fail=hard_fail,
            hard_fail_triggered=False,
        )
        for name, max_score, hard_fail in specs
    ]


