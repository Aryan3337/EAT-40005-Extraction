def save_evaluation_log(
    result: EvaluationResult,
    log_type: str
) -> Path:
    LOG_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    if log_type == "approval":
        subdir = APPROVED_DIR
    elif log_type == "rejection":
        subdir = REJECTED_DIR
    elif log_type == "review":
        subdir = REVIEW_DIR
    else:
        subdir = LOG_DIR

    subdir.mkdir(
        parents=True,
        exist_ok=True
    )

    safe_name = re.sub(
        r"[^\w\-]",
        "_",
        Path(result.paper_path).stem
    )[:50]

    log_path = subdir / (
        f"{result.timestamp}_{log_type}_{safe_name}.json"
    )

    hard_fail_names = [
        criterion.name
        for criterion in result.hard_fail_criteria
    ]

    data = {
        "paper": result.paper_path,
        "paper_name": result.paper_name,
        "timestamp": result.timestamp,
        "model_used": result.model_used,
        "outcome": result.outcome.value,
        "accumulated_score": result.accumulated_score,
        "total_score": result.total_score,
        "max_possible": result.max_possible,
        "score_pct": result.score_pct,
        "hard_fail_count": len(
            result.hard_fail_criteria
        ),
        "hard_fail_criteria": hard_fail_names,
        "thresholds": {
            "reject_below": REJECT_THRESHOLD,
            "manual_review_band": (
                f"{REJECT_THRESHOLD}-{REVIEW_THRESHOLD}"
            ),
            "auto_approve_above": REVIEW_THRESHOLD,
        },
        "rejection_reason": result.rejection_reason,
        "review_reason": result.review_reason,
        "criteria": [
            {
                "name": criterion.name,
                "score": criterion.score,
                "max_score": criterion.max_score,
                "passed": criterion.passed,
                "hard_fail": criterion.hard_fail,
                "hard_fail_triggered": (
                    criterion.hard_fail_triggered
                ),
                "evaluated_by": criterion.evaluated_by,
                "justification": criterion.justification,
                "flags": criterion.flags,
            }
            for criterion in result.criteria
        ],
        "next_steps": (
            "REJECTED — paper skipped. Review the hard-fail criteria and "
            "criterion justifications before reconsidering this source."
            if log_type == "rejection"
            else
            "MANUAL REVIEW — extraction is held pending human review."
            if log_type == "review"
            else
            "APPROVED — paper passed the scoreboard and is ready for "
            "knowledge graph extraction."
        ),
    }

    log_path.write_text(
        json.dumps(
            data,
            indent=2,
            ensure_ascii=False
        ),
        encoding="utf-8"
    )

    return log_path


def append_review_queue(
    result: EvaluationResult
) -> Path:
    write_header = not REVIEW_QUEUE_FILE.exists()

    with open(
        REVIEW_QUEUE_FILE,
        "a",
        newline="",
        encoding="utf-8"
    ) as file:
        writer = csv.writer(file)

        if write_header:
            writer.writerow([
                "timestamp",
                "paper_name",
                "paper_path",
                "model_used",
                "accumulated_score",
                "max_possible",
                "score_pct",
                "hard_fail_criteria",
                "review_reason",
                "status",
                "override_by",
                "override_note",
            ])

        writer.writerow([
            result.timestamp,
            result.paper_name,
            result.paper_path,
            result.model_used,
            result.accumulated_score,
            result.max_possible,
            result.score_pct,
            "; ".join(
                criterion.name
                for criterion in result.hard_fail_criteria
            ),
            result.review_reason,
            "PENDING",
            "",
            "",
        ])

    return REVIEW_QUEUE_FILE


