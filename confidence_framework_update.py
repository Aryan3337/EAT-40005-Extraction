NEGATION_CUES = [
    "no ",
    "not ",
    "without ",
    "lack of ",
    "lacking ",
    "absence of ",
    "none of ",
]


def _has_unnegated_match(
    text_lower: str,
    phrase: str,
    window_chars: int = 40
) -> bool:
    start = 0

    while True:
        idx = text_lower.find(phrase, start)

        if idx == -1:
            return False

        preceding = text_lower[
            max(0, idx - window_chars):idx
        ]

        if not any(
            cue in preceding
            for cue in NEGATION_CUES
        ):
            return True

        start = idx + len(phrase)


def _dedupe_substring_hits(
    hits: List[str]
) -> List[str]:
    hits_sorted = sorted(
        set(hits),
        key=len,
        reverse=True
    )

    kept: List[str] = []

    for hit in hits_sorted:
        if not any(
            hit != kept_hit and hit in kept_hit
            for kept_hit in kept
        ):
            kept.append(hit)

    return kept


def check_data_driven_evidence(
    text_lower: str
) -> Dict[str, Any]:
    raw_data_hits = [
        signal
        for signal in DATA_DRIVEN_SIGNALS
        if _has_unnegated_match(
            text_lower,
            signal
        )
    ]

    raw_experience_hits = [
        signal
        for signal in EXPERIENCE_REPORT_SIGNALS
        if signal in text_lower
    ]

    data_hits = _dedupe_substring_hits(
        raw_data_hits
    )

    experience_hits = _dedupe_substring_hits(
        raw_experience_hits
    )

    if experience_hits and not data_hits:
        verdict = "experience_report"

    elif (
        experience_hits
        and data_hits
        and len(experience_hits) > len(data_hits)
    ):
        verdict = "experience_leaning"

    elif data_hits:
        verdict = "data_driven"

    else:
        verdict = "undetermined"

    return {
        "verdict": verdict,
        "data_driven_signals_found": data_hits,
        "experience_signals_found": experience_hits,
    }


def check_experience_report_identification(
    text_lower: str
) -> CriterionResult:
    """
    Criterion 7 — maximum 5, no hard fail.

    This keeps the existing data-driven vs experience-report signal
    detection, but exposes it as its own criterion because the new
    framework explicitly requires Experience Report Identification.
    """

    scan = check_data_driven_evidence(text_lower)

    verdict = scan["verdict"]
    experience_hits = scan[
        "experience_signals_found"
    ]
    data_hits = scan[
        "data_driven_signals_found"
    ]

    if verdict == "experience_report":
        score = 5
        justification = (
            "Paper appears narrative/experiential with no clear "
            "data-collection or methodology evidence."
        )

    elif verdict == "experience_leaning":
        score = 3
        justification = (
            "Experiential or reflective language is stronger than the "
            "detected methodology/data-driven signals."
        )

    elif verdict == "data_driven":
        score = 0
        justification = (
            "Paper appears to be a conventional data-driven research "
            "paper rather than an experience report."
        )

    else:
        score = 0
        justification = (
            "No strong experience-report or data-driven signals were "
            "detected."
        )

    flags = []

    if experience_hits:
        flags.append(
            f"Experience signals: {experience_hits[:8]}"
        )

    if data_hits:
        flags.append(
            f"Data-driven signals: {data_hits[:8]}"
        )

    return CriterionResult(
        name="Experience Report Identification",
        score=score,
        max_score=5,
        passed=True,
        justification=justification,
        evaluated_by="code",
        flags=flags,
        hard_fail=False,
        hard_fail_triggered=False,
    )


def check_domain_relevance(
    text_lower: str
) -> CriterionResult:
    found_keywords = [
        keyword
        for keyword in COMMUNITY_KEYWORDS
        if keyword.lower() in text_lower
    ]

    relevant = len(found_keywords) > 0

    if relevant:
        justification = (
            "Community/domain-related keywords were detected: "
            f"{found_keywords}."
        )
    else:
        justification = (
            "No configured community/domain keywords were detected. "
            "This criterion is logged only and does not affect scoring."
        )

    return CriterionResult(
        name="Domain Relevance",
        score=0,
        max_score=0,
        passed=True,
        justification=justification,
        evaluated_by="code",
        flags=[] if relevant else [
            "No configured domain keywords found"
        ],
        hard_fail=False,
        hard_fail_triggered=False,
    )


